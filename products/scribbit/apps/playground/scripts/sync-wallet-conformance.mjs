// Snapshot the signet-relevant rows of the wallet conformance matrix (DegentClub/specs conformance/wallets.yaml)
// into src/data/wallet-signet.json, with provenance. The app READS statuses from the snapshot; it never hard-codes
// them, and it computes every count it shows. Re-run after the matrix changes:
//   pnpm --filter @bsh/scribbit-playground sync:wallets [path/to/wallets.yaml]
//   pnpm --filter @bsh/scribbit-playground sync:wallets --check   (exit 1 when the snapshot is stale)
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const check = args.includes('--check');
const source = args.find((a) => !a.startsWith('--')) ?? process.env.WALLETS_YAML ?? join(here, '../../../../../../specs/conformance/wallets.yaml');
const out = join(here, '../src/data/wallet-signet.json');

/** The capabilities the playground's step 1 needs to explain a wallet on signet. */
export const CAPS = ['connect', 'network-signet', 'sign-psbt', 'taproot-tweaked', 'taproot-untweaked', 'push-tx'];

export function snapshot(yamlText) {
  const doc = parse(yamlText);
  return {
    $comment: 'GENERATED by scripts/sync-wallet-conformance.mjs from DegentClub/specs conformance/wallets.yaml. Do not edit.',
    source: { repo: 'DegentClub/specs', path: 'conformance/wallets.yaml', asOf: doc.asOf, walletKitCommit: doc.walletKit?.commit ?? null },
    capabilities: CAPS,
    wallets: doc.wallets.map((w) => ({
      id: w.id,
      name: w.name,
      networks: w.networks,
      results: Object.fromEntries(CAPS.map((c) => [c, { status: w.results[c]?.status ?? 'unknown', note: w.results[c]?.note ?? null }])),
    })),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (!existsSync(source)) {
    console.error(`wallets.yaml not found at ${source} (pass a path or set WALLETS_YAML)`);
    process.exit(check ? 0 : 2);
  }
  const next = `${JSON.stringify(snapshot(readFileSync(source, 'utf8')), null, 2)}\n`;
  if (check) {
    const cur = existsSync(out) ? readFileSync(out, 'utf8') : '';
    if (cur !== next) {
      console.error('src/data/wallet-signet.json is stale: run `pnpm --filter @bsh/scribbit-playground sync:wallets`');
      process.exit(1);
    }
    console.log('wallet-signet.json is fresh');
  } else {
    writeFileSync(out, next);
    console.log(`wrote ${out}`);
  }
}
